#include <iostream>
using namespace std;
int main()
{
    int a;
    float b;
    double c;
    char d;
    cout << "the size of integer:" << sizeof(a) << endl;
    cout << "the size of float:" << sizeof(b) << endl;
    cout << "the size of double:" << sizeof(c) << endl;
    cout << "the size of char:" << sizeof(d) << endl;
    return 0;
}
